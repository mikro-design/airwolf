"""Several LTE cells in one capture: every cell followed, not only the strongest.

Cells are generated by the pinned PHY transmitter, summed with independent
power, timing and carrier offset, quantized to HackRF int8 and received live
(real-time paced) and from a selected IQ file. This is integration evidence for
following several cells at once, not conformance or interference-rejection
evidence. A cell search reports one candidate per PSS identity (PCI mod 3), so
a weaker cell with the same identity as a stronger one is not found.
"""
import collections
import json
from pathlib import Path
import checked_subprocess as subprocess
import sys
import tempfile
import numpy as np
from scipy.signal import resample_poly

fixture, si_fixture, feed, worker = sys.argv[1:5]
rate = 8000000
rates = {6: 1920000, 15: 3840000, 25: 5760000, 50: 11520000, 75: 15360000, 100: 23040000}
rng = np.random.default_rng(0x3CE11202)
sib2 = bytes.fromhex('000149001250400800094000a03f01000a7fc9800104286c000c')


def sib1():
    # Same SIB1 as scheduled_information.py: SIB2 in the first SI, period 16 frames.
    bits = ''
    def put(n, v):
        nonlocal bits; bits += f'{v:0{n}b}'
    put(2, 1); put(1, 0); put(1, 0); put(1, 0); put(1, 0); put(3, 0)
    put(1, 1); put(4, 0); put(4, 0); put(4, 1); put(1, 0); put(4, 0); put(4, 1); put(1, 1)
    put(16, 1); put(28, 0x1a2d401); put(3, 4); put(1, 0); put(6, 0); put(6, 6)
    put(5, 0); put(3, 1); put(5, 0)
    put(3, 6); put(5, 8)
    return int(bits.ljust((len(bits) + 7) // 8 * 8, '0'), 2).to_bytes((len(bits) + 7) // 8, 'big')


def combine(cells, seconds, directory, si=False):
    """cells: (pci, prb, dB of its centre 1.08 MHz, delay ms, CFO Hz)."""
    n = int(rate * seconds); total = np.zeros(n, np.complex128)
    for pci, prb, db, delay_ms, cfo in cells:
        cf = Path(directory) / f'{pci}.cf32'
        if si:
            s1 = Path(directory) / 'sib1.bin'; s1.write_bytes(sib1())
            subprocess.run([si_fixture, str(cf), str(prb), str(pci), '2', str(int(seconds * 1000) + 20),
                            'scheduled', '0', '0', '3', str(s1)], check=True, capture_output=True)
        else:
            subprocess.run([fixture, str(cf), str(pci), str(prb), str(int(seconds * 1000) + 20)],
                           check=True, capture_output=True)
        x = np.fromfile(cf, np.complex64).astype(np.complex128)
        # The MIB fixture writes only the centre six resource blocks at
        # 1.92 MS/s; the SI fixture writes the whole cell bandwidth.
        source = rates[prb] if si else rates[6]
        g = np.gcd(rate, source); x = resample_poly(x, rate // g, source // g)
        # Level by the centre six resource blocks, where synchronization and
        # PBCH are: total power would make wide cells look weaker than they are.
        spectrum = np.fft.fft(x[:rate // 10]); f = np.fft.fftfreq(len(spectrum), 1 / rate)
        centre = np.mean(abs(spectrum[abs(f) < 540000]) ** 2) / len(spectrum)
        x *= 10 ** (db / 20) / np.sqrt(centre * 1080000 / rate)
        d = int(rate * delay_ms / 1000); x = np.r_[np.zeros(d), x][:n]
        x *= np.exp(2j * np.pi * cfo * np.arange(len(x)) / rate)
        total[:len(x)] += x
    total *= 28 / np.sqrt(np.mean(abs(total) ** 2))
    total += .5 * (rng.normal(size=n) + 1j * rng.normal(size=n))
    iq = Path(directory) / 'cells.iq'; data = np.empty(2 * n, np.int8)
    data[::2] = np.clip(np.rint(total.real), -127, 127); data[1::2] = np.clip(np.rint(total.imag), -127, 127)
    data.tofile(iq)
    return iq


def live(iq):
    run = subprocess.run([feed, str(rate), str(iq)], capture_output=True, text=True, timeout=60)
    assert run.returncode == 0, run.stderr[-1500:]
    assert 'dropped_samples=0' in run.stderr, run.stderr[-500:]
    return [json.loads(line) for line in run.stdout.splitlines()]


def check_progression(frames, pci):
    mine = [f for f in frames if f['pci'] == pci]
    for a, b in zip(mine, mine[1:]):
        frames_apart = round((b['endSample'] - a['endSample']) / (rate / 100))
        assert frames_apart >= 1 and (b['sfn'] - a['sfn']) % 1024 == frames_apart % 1024, (pci, a, b)
    return mine


with tempfile.TemporaryDirectory(prefix='airwolf-lte-cells-') as directory:
    seconds = 3.0
    expected = int(seconds * 100)
    # Three PSS identities, a 6 dB spread, staggered timing and carrier offsets
    # of both signs, cells of three bandwidths.
    cells = [(42, 6, 0, 0, 1500), (100, 25, -3, 2.3, -2000), (302, 50, -6, 4.1, 700)]
    frames = live(combine(cells, seconds, directory))
    counts = collections.Counter(f['pci'] for f in frames)
    assert set(counts) == {42, 100, 302}, counts
    for pci, prb, *_ in cells:
        mine = check_progression(frames, pci)
        assert len(mine) >= expected * .9, (pci, counts)
        assert all(f['prb'] == prb for f in mine), (pci, {f['prb'] for f in mine})
    print(f'live, three cells at 0/-3/-6 dB: MIBs per cell {dict(counts)} of about {expected}', flush=True)

    # The strongest cell loses nothing to following the others.
    alone = collections.Counter(f['pci'] for f in live(combine(cells[:1], seconds, directory)))
    assert counts[42] >= alone[42] - 2, (counts, alone)

    # Same PSS identity: only the stronger cell is found, and fully followed.
    same = [(42, 6, 0, 0, 1500), (45, 6, -6, 2.3, -2000)]
    frames = live(combine(same, seconds, directory))
    counts = collections.Counter(f['pci'] for f in frames)
    assert set(counts) == {42} and counts[42] >= expected * .9, counts
    print(f'same PSS identity (42, 45): only the stronger cell, {counts[42]} MIBs', flush=True)

    # Real air: the recorded 1860 MHz FDD capture holds two cells with
    # different PSS identities (PCI 142 and 86), each with its own MIBs.
    capture = Path(__file__).resolve().parents[2] / 'tests' / 'fixtures' / 'lte-cell-scanner' / 'fdd-1860.ci8'
    v = np.fromfile(capture, np.int8).astype(np.float32); x = v[::2] + 1j * v[1::2]
    for real_rate in (8000000, 10000000, 16000000, 20000000):
        g = np.gcd(real_rate, 1920000); y = resample_poly(x, real_rate // g, 1920000 // g)
        iq = Path(directory) / 'real.iq'; data = np.empty(2 * len(y), np.int8)
        data[::2] = np.clip(np.rint(y.real), -127, 127); data[1::2] = np.clip(np.rint(y.imag), -127, 127)
        data.tofile(iq)
        # A third of real time, as recorded.py: correctness, not throughput.
        run = subprocess.run([feed, str(real_rate), str(iq), '3'], capture_output=True, text=True, timeout=60)
        assert run.returncode == 0 and 'dropped_samples=0' in run.stderr, run.stderr[-1000:]
        frames = [json.loads(line) for line in run.stdout.splitlines()]
        counts = collections.Counter(f['pci'] for f in frames)
        assert set(counts) == {86, 142} and min(counts.values()) >= 60, (real_rate, counts)
        for pci in counts:
            mine = [f for f in frames if f['pci'] == pci]
            for a, b in zip(mine, mine[1:]):
                apart = round((b['endSample'] - a['endSample']) / (real_rate / 100))
                assert apart >= 1 and (b['sfn'] - a['sfn']) % 1024 == apart % 1024, (real_rate, pci, a, b)
        print(f'recorded FDD 1860 MHz, {real_rate / 1e6:g} MS/s: MIBs per cell {dict(counts)}', flush=True)

    # System information per cell from one selected IQ interval. The selection
    # worker returns at most 256 packets, so keep the interval short.
    seconds = .5
    # Loaded PDSCH of each cell overlaps the others' centre band here: keep a
    # 3 dB spread (the live case above covers 6 dB without data load).
    cells = [(42, 25, 0, 0, 1500), (100, 15, -2, 2.3, -1000), (302, 6, -3, 4.1, 1500)]
    iq = combine(cells, seconds, directory, si=True)
    run = subprocess.run([worker, 'decode', str(iq), '0', str(iq.stat().st_size // 2), 'lte', str(rate),
                          '2660000000', '2660000000', '1m', '2391391958', '5592405'],
                         capture_output=True, text=True, timeout=120)
    assert run.returncode == 0, run.stderr[-1500:]
    packets = json.loads(run.stdout)['packets']
    assert len(packets) < 256, len(packets)
    expected_sib1 = sib1()
    for pci, prb, *_ in cells:
        mine = [p for p in packets if p['ltePci'] == pci]
        mib = [p for p in mine if p['lteChannel'] == 'bcch-bch']
        dl = [bytes(p['bytes']) for p in mine if p['lteChannel'] == 'bcch-dl-sch']
        first = [b for b in dl if b[0] & 0xc0]
        system = [b for b in dl if not b[0] & 0xc0]
        assert len(mib) >= 40 and all(p['ltePrb'] == prb for p in mib), (pci, len(mib))
        assert first and all(b.startswith(expected_sib1) for b in first), (pci, first)
        assert system and all(b.startswith(sib2) for b in system), (pci, system)
        print(f'PCI {pci}, {prb} PRB: {len(mib)} MIBs, {len(first)} SIB1, {len(system)} SI messages', flush=True)
