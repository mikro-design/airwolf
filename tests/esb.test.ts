test.skipIf(!existsSync(radioBinary) || !existsSync(iqBinary))(
  'promiscuous live ESB → frame IQ → replay for the confirmed address',
  async () => {
    const directory = await mkdtemp(join(tmpdir(), 'airwolf-esb-'));
    const names = ['AIRWOLF_RADIO_PATH', 'AIRWOLF_FAKE_IQ_FILE', 'AIRWOLF_IQ_PATH'] as const;
    const saved = names.map((name) => process.env[name]);
    try {
      const file = join(directory, 'esb.iq');
      execFileSync(python, ['-c', generator, file], { timeout: 60000 });
      process.env.AIRWOLF_RADIO_PATH = radioBinary;
      process.env.AIRWOLF_FAKE_IQ_FILE = file;
      process.env.AIRWOLF_IQ_PATH = iqBinary;
      const packets: any[] = [];
      let failed = '';
      // Wired as electron/main.cjs wires them.
      let service: any;
      const radio = createRadio(
        () => {},
        (status: any) => {
          if (status.state === 'error') failed = status.message;
          service?.onStatus(status);
        },
        undefined,
        (packet: any) => {
          packets.push(packet);
          service?.onPacket(packet);
        },
        (recording: any) => service?.onRecording(recording),
      );
      service = createIqCapture({
        directory: join(directory, 'takes'),
        radio,
        emit: () => {},
      });
      await radio.start(config);
      const deadline = Date.now() + 15000;
      while (packets.length < 2 && !failed && Date.now() < deadline)
        await new Promise((r) => setTimeout(r, 50));
      expect(failed).toBe('');
      await radio.pause();
      expect(packets.map((p) => p.bytes)).toEqual([
        data16,
        [231, 58, 92, 25, 178, 7, 0, 0x42, ...packets[1].bytes.slice(-2)],
      ]);
      expect(packets[1]).toMatchObject({ integrity: 'valid', esbAddressWidth: 5, phy: '2m' });
      // The second frame alone cannot be confirmed again in a one-frame take;
      // the snapshot records the address it was received with.
      const selected = await service.frame(packets[1].iqRef);
      await radio.stop();
      const take = await service.take(selected.id);
      expect(take.config.esb).toEqual({ rate: '2m', address: 'e73a5c19b2', crc: 2 });
      const replay = await service.decode(take.id, 0, take.samples, undefined, selected.packet);
      expect(replay.packets).toHaveLength(1);
      expect(replay.packets[0]).toMatchObject({
        bytes: packets[1].bytes,
        integrity: 'valid',
        esbAddressWidth: 5,
        esbCrcBytes: 2,
        phy: '2m',
        referenceIndex: 0,
      });

      // A recorded promiscuous take: one frame's span alone holds no second
      // frame to confirm its address, so selecting it replays for its address.
      await service.start(config, 0.1);
      const until = Date.now() + 20000;
      let state = await service.list();
      while ((state.active || state.captures.length < 2) && Date.now() < until) {
        await new Promise((r) => setTimeout(r, 100));
        state = await service.list();
      }
      const recorded = await service.take(state.captures.find((t: any) => t.reason !== 'frame').id);
      expect(recorded.config.esb).toEqual({ rate: '2m', crc: 2 });
      const index = recorded.packets.findIndex((p: any) => p.bytes[5] === 7);
      expect(index).toBeGreaterThanOrEqual(0);
      const p = recorded.packets[index];
      const span = [Math.max(0, p.firstSample - 800), p.endSample + 800];
      expect((await service.decode(recorded.id, span[0], span[1])).packets).toEqual([]);
      const own = await service.decode(recorded.id, span[0], span[1], undefined, index);
      expect(own.config.esb).toEqual({ rate: '2m', address: 'e73a5c19b2', crc: 2 });
      expect(own.packets).toMatchObject([
        { bytes: p.bytes, integrity: 'valid', referenceIndex: index },
      ]);
    } finally {
      names.forEach((name, i) =>
        saved[i] === undefined ? delete process.env[name] : (process.env[name] = saved[i]),
      );
      await rm(directory, { recursive: true, force: true });
    }
  },
  60000,
);
